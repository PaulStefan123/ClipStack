import AppKit
import Combine

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String
    var date: Date
    var appBundleID: String?
    var appName: String?

    /// Non-empty, trimmed lines of the copied text.
    var lines: [String] {
        text.components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
    }

    /// Short preview shown in the list (first two non-empty lines).
    var preview: String {
        lines.prefix(2).map { String($0.prefix(300)) }.joined(separator: "\n")
    }
}

/// Watches the system pasteboard and keeps the latest copies, newest first.
final class ClipboardStore: ObservableObject {
    static let maxItems = 10

    @Published private(set) var items: [ClipItem] = []

    /// Copies older than this are removed automatically (nil = keep).
    var maxAge: TimeInterval? {
        didSet { purgeExpired() }
    }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let fileURL: URL

    /// Pasteboard markers used by password managers and other apps to say
    /// "don't record this" (see nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipStack", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("history.json")
        lastChangeCount = pasteboard.changeCount
        load()
    }

    func start() {
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        purgeExpired()
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        let app = NSWorkspace.shared.frontmostApplication
        insert(ClipItem(text: text, date: Date(), appBundleID: app?.bundleIdentifier, appName: app?.localizedName))
    }

    private func insert(_ item: ClipItem) {
        items.removeAll { $0.text == item.text }
        items.insert(item, at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
        save()
    }

    /// Puts an item back on the system pasteboard and moves it to the top.
    func copyToPasteboard(_ item: ClipItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount

        var moved = item
        moved.date = Date()
        items.removeAll { $0.id == item.id }
        items.insert(moved, at: 0)
        save()
    }

    func remove(at index: Int) {
        guard items.indices.contains(index) else { return }
        items.remove(at: index)
        save()
    }

    func purgeExpired() {
        guard let maxAge else { return }
        let cutoff = Date().addingTimeInterval(-maxAge)
        let kept = items.filter { $0.date >= cutoff }
        guard kept.count != items.count else { return } // avoid republishing every poll
        items = kept
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    // MARK: Persistence (local only, readable by the current user only)

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = Array(saved.prefix(Self.maxItems))
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}
